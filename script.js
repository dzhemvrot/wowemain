let currentLang = 'en';

function changeLanguage(lang) {
  currentLang = lang;

  // Update active button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Translate static elements
  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Refresh dynamic content
  document.getElementById("summerCountdown").innerHTML = daysUntilSummer();
  document.getElementById("BDayCountdown").innerHTML = daysUntilBDay();
  document.getElementById("summerCountdownMobile").innerHTML = daysUntilSummer();
  document.getElementById("BDayCountdownMobile").innerHTML = daysUntilBDay();
  document.getElementById("AgeCounter").innerHTML = currentAge();
}

// ==================== COUNTDOWN FUNCTIONS ====================

function daysUntilSummer() {
  const today = new Date();
  const year = today.getFullYear();

  let summerStart = new Date(year, 5, 1); // June 1
  const summerEnd = new Date(year, 7, 31);   // July 31

  if (today >= summerStart && today <= summerEnd) {
    return translations[currentLang]["summer-now"];
  }

  if (today > summerEnd) {
    summerStart = new Date(year + 1, 5, 1);
  }

  const diffTime = summerStart - today;
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  return translations[currentLang]["summer-countdown"]
    .replace("{days}", diffDays);
}

function daysUntilBDay() {
  const today = new Date();
  const year = today.getFullYear();

  let BDay = new Date(year, 5, 30); // June 30

  if (today.getMonth() === 5 && today.getDate() === 30) {
    return translations[currentLang]["bday-today"];
  }

  if (today > BDay) {
    BDay = new Date(year + 1, 5, 30);
  }

  const diffTime = BDay - today;
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  return translations[currentLang]["bday-countdown"]
    .replace("{days}", diffDays);
}

function currentAge() {
  const dob = new Date("2007-06-30");
  const month_diff = Date.now() - dob.getTime();
  const age_dt = new Date(month_diff);
  const year = age_dt.getUTCFullYear();
  let age = Math.abs(year - 1970);

  const currentyear = new Date().getFullYear();
  const willbe = currentyear - 2007;

  let returntext = translations[currentLang]["age-current"]
    .replace("{age}", age);

  if (willbe !== age) {
    returntext += translations[currentLang]["age-will-be"]
      .replace("{willbe}", willbe);
  } else {
    returntext += ". ";
  }
  return returntext;
}

